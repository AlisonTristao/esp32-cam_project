"""Generates include/dev_key_l_generated.h, a bally.key file image (KeyStore
format, key_e + key_l already derived) baked into a C++ header.

TEMPORARY BENCH-ONLY SHORTCUT: this device does not have an SD card yet, so
it cannot read bally.key the real way (KeyStore::load_from_card(), the same
path bally_OS uses). Until a card is provisioned and inserted, main.cpp falls
back to loading this embedded blob instead -- see the DEV_EMBEDDED_KEY_L
#ifdef there. Remove that fallback AND stop calling this script (drop the
`pre:scripts/gen_dev_key.py` line in platformio.ini) once a real card is in
use; this key is a fixed, versioned test password ("alison"), not a secret
worth protecting.

Reuses bally_OS/scripts/provision_key.py's own --password-e/--password-l
non-interactive flags (built for exactly this: rebuilding a golden test
vector without a TTY) instead of reimplementing PBKDF2/HMAC/CRC32 here, so
this can never drift from the real derivation bally_dongle's `hub
-set_key_l` and TraceView both reproduce.

Runs unconditionally at module scope (SCons execs extra_scripts, an
`if __name__ == "__main__"` guard would never fire under SCons -- same
reasoning as check_channel_contract.py's own docstring) and is cheap/
idempotent, so it always regenerates the header regardless of whether the
current build actually defines DEV_EMBEDDED_KEY_L.
"""
Import("env")

import subprocess
import sys
from pathlib import Path

# Bench-only password for BOTH channels. Channel B (key E) is not even used
# by this device yet -- its value here is irrelevant beyond satisfying the
# two-key file format.
_DEV_PASSWORD = "alison"

_project_dir = Path(env["PROJECT_DIR"])

_provision_script = (_project_dir / ".." / "bally_OS" / "scripts" /
                     "provision_key.py").resolve()
_header_path = _project_dir / "include" / "dev_key_l_generated.h"
_key_blob_path = _project_dir / ".pio" / "dev_bally.key"


def _generate():
    if not _provision_script.is_file():
        print("gen_dev_key.py: %s not found, skipping (no sibling bally_OS "
              "checkout?)" % _provision_script, file=sys.stderr)
        return

    _key_blob_path.parent.mkdir(parents=True, exist_ok=True)
    subprocess.run(
        [sys.executable, str(_provision_script), str(_key_blob_path),
         "--force", "--password-e", _DEV_PASSWORD, "--password-l", _DEV_PASSWORD],
        check=True,
    )

    blob = _key_blob_path.read_bytes()

    lines = [
        "#ifndef DEV_KEY_L_GENERATED_H",
        "#define DEV_KEY_L_GENERATED_H",
        "",
        "// GENERATED by scripts/gen_dev_key.py -- DO NOT EDIT BY HAND.",
        "// Bench-only key (fixed test password), NOT for any real deployment.",
        "// See that script's docstring for how to remove this shortcut.",
        "#include <cstdint>",
        "",
        "inline constexpr std::uint8_t kDevKeyFile[96] = {",
    ]
    for offset in range(0, len(blob), 12):
        chunk = blob[offset:offset + 12]
        lines.append("    " + ", ".join("0x%02X" % byte for byte in chunk) + ",")
    lines.append("};")
    lines.append("")
    lines.append("#endif  // DEV_KEY_L_GENERATED_H")

    _header_path.parent.mkdir(parents=True, exist_ok=True)
    _header_path.write_text("\n".join(lines) + "\n")


_generate()
